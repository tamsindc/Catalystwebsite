#!/usr/bin/env python3
"""Merge and check fishpond recipes in data/recipes/*.json, then write data/workflows.js for the site.

Usage: python3 scripts/build_recipes.py
"""
import datetime as dt
import glob
import json
import re
import sys

TOPICS = {
    "Email & Inbox": "work", "Meetings & Calendar": "work", "Planning & Productivity": "work",
    "Customer Support": "work", "Sales & Leads": "work", "HR & Hiring": "work",
    "Marketing & Social": "work", "Content & Writing": "work", "Video, Image & Voice": "work",
    "Research & News": "work", "Documents & Data": "work", "Small Business Admin": "work",
    "Food & Home": "life", "Travel": "life", "Health & Fitness": "life",
    "Money": "life", "Learning": "life", "Careers": "life", "Personal Assistant": "life",
}
LEVELS = {"Beginner", "Intermediate", "Advanced"}
TRIGGERS = {"schedule", "new_email", "new_file", "new_row", "form_submitted", "calendar_event", "message_received", "manual"}
ACTIONS = {"ai.generate", "ai.summarize", "ai.classify", "ai.extract", "email.draft", "email.send", "email.label",
           "sheet.append", "sheet.update", "doc.create", "calendar.create", "list.add", "notify", "web.fetch",
           "file.save", "message.send"}
BANNED = re.compile(r"\bn8n\b|zapier|make\.com|webhook|\bapi\b|python|javascript|supercharge|revolutioni[sz]e|seamless", re.I)


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")[:60]


def text(v, limit=None):
    v = re.sub(r"\s+", " ", str(v or "")).strip()
    return v[:limit].rstrip() if limit else v


def check(r, src):
    problems = []
    for k in ("t", "d", "cat", "lvl", "steps"):
        if not r.get(k):
            problems.append(f"missing {k}")
    if r.get("cat") not in TOPICS:
        problems.append(f"unknown topic {r.get('cat')!r}")
    if r.get("lvl") not in LEVELS:
        problems.append(f"bad level {r.get('lvl')!r}")
    steps = r.get("steps") or []
    if not 2 <= len(steps) <= 7:
        problems.append(f"{len(steps)} steps")
    if not any(s.get("p") for s in steps):
        problems.append("no prompt")
    return problems


def clean(r):
    auto = r.get("auto") or {}
    trig = auto.get("trigger") or {}
    return {
        "id": slug(r["t"]),
        "t": text(r["t"], 90),
        "d": text(r["d"], 200),
        "cat": r["cat"],
        "side": TOPICS[r["cat"]],
        "lvl": r["lvl"],
        "mins": max(1, min(120, int(r.get("mins") or 10))),
        "tools": [text(t, 30) for t in (r.get("tools") or [])][:4] or ["AI assistant"],
        "when": text(r.get("when"), 80) or "When you need it",
        "steps": [{k: text(v) for k, v in s.items() if k in ("h", "b", "p") and v} for s in r["steps"]][:7],
        "example": text(r.get("example"), 400),
        "tips": [text(t, 220) for t in (r.get("tips") or [])][:3],
        "auto": {
            "trigger": {"type": trig.get("type") if trig.get("type") in TRIGGERS else "manual", "detail": text(trig.get("detail"), 120)},
            "actions": [{"type": a.get("type"), "detail": text(a.get("detail"), 140)} for a in (auto.get("actions") or []) if a.get("type") in ACTIONS][:6],
        },
    }


def main():
    files = sorted(glob.glob("data/recipes/*.json"))
    if not files:
        sys.exit("No recipe files in data/recipes/")
    items, seen, warnings = [], set(), []
    for f in files:
        try:
            data = json.load(open(f, encoding="utf-8"))
        except json.JSONDecodeError as e:
            warnings.append(f"{f}: invalid JSON ({e})")
            continue
        for r in data:
            problems = check(r, f)
            if problems:
                warnings.append(f"{f}: dropped {r.get('t')!r}: {', '.join(problems)}")
                continue
            c = clean(r)
            if c["id"] in seen:
                warnings.append(f"{f}: duplicate {c['t']!r}")
                continue
            blob = json.dumps(c, ensure_ascii=False)
            if BANNED.search(blob):
                warnings.append(f"{f}: check wording in {c['t']!r}: {BANNED.search(blob).group(0)!r}")
            seen.add(c["id"])
            items.append(c)

    # Featured order: interleave topics, quickest wins first within each topic.
    by_topic = {}
    for it in items:
        by_topic.setdefault(it["cat"], []).append(it)
    order = {"Beginner": 0, "Intermediate": 1, "Advanced": 2}
    for lst in by_topic.values():
        lst.sort(key=lambda x: (order[x["lvl"]], x["mins"]))
    featured = []
    while any(by_topic.values()):
        for t in TOPICS:
            if by_topic.get(t):
                featured.append(by_topic[t].pop(0))

    meta = {"built": dt.date.today().isoformat(), "count": len(featured)}
    with open("data/workflows.js", "w", encoding="utf-8") as fh:
        fh.write("// Generated by scripts/build_recipes.py from data/recipes/*.json. Edit the recipes, not this file.\n")
        fh.write("window.FISHPOND = ")
        json.dump({"meta": meta, "items": featured}, fh, ensure_ascii=False, separators=(",", ":"))
        fh.write(";\n")

    counts = {}
    for it in featured:
        counts[it["cat"]] = counts.get(it["cat"], 0) + 1
    print(f"Wrote {len(featured)} recipes to data/workflows.js")
    for t in TOPICS:
        print(f"  {counts.get(t, 0):>3}  {t}")
    lv = {}
    for it in featured:
        lv[it["lvl"]] = lv.get(it["lvl"], 0) + 1
    print("  levels:", lv)
    if warnings:
        print(f"\n{len(warnings)} warnings:")
        for w in warnings:
            print("  -", w)


if __name__ == "__main__":
    main()
